#!/usr/bin/env node
/**
 * build-page.js — turn a pandoc-generated HTML fragment into a site-ready notes page.
 *
 * Usage:
 *   node build-page.js --input <pandoc.html> --output <final.html> \
 *        --title "Chapter 5: GLM MLE" [--subtitle "中文副标题"] \
 *        [--back "/teachings/mth303/" --back-label "MTH303"] \
 *        [--kind math|plain] [--css path/to/page-style.css]
 *
 * What it does, in order:
 *   1. strips pandoc's own <style> blocks
 *   2. splits stepbox/keybox/warnbox/boardbox panels into .box-title + .box-body
 *   3. replaces unresolved cross references ([eq:…], ??) with a neutral label
 *   4. converts leftover raw-TeX <span class="math"> into plain text
 *   5. wraps every <table> in a horizontally scrollable .table-wrap
 *   6. injects the shared page style, left TOC, back link and AI footer
 */
const fs = require("fs");
const path = require("path");

/* ------------------------------ args ------------------------------ */
const args = {};
for (let i = 2; i < process.argv.length; i += 2) {
  const k = process.argv[i].replace(/^--/, "");
  args[k] = process.argv[i + 1];
}
const input = args.input;
const output = args.output || path.join(path.dirname(input || "."), "final.html");
const title = args.title || "Course notes";
const subtitle = args.subtitle || "";
const back = args.back || "/teachings/mth303/";
const backLabel = args["back-label"] || "MTH303";
const cssPath = args.css || path.join(__dirname, "..", "assets", "page-style.css");

if (!input || !fs.existsSync(input)) {
  console.error("usage: node build-page.js --input <pandoc.html> --output <final.html> --title \"…\"");
  process.exit(1);
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
let html = fs.readFileSync(input, "utf8");

/* ------------------------- 1. drop pandoc css ------------------------- */
html = html.replace(/<style[^>]*>[\s\S]*?<\/style>/gi, "");

/* --------------- 2. panel title/body split (nested-span aware) --------------- */
function matchSpanEnd(h, start) {
  let depth = 0, i = start;
  while (i < h.length) {
    const o = h.indexOf("<span", i), c = h.indexOf("</span>", i);
    if (c === -1) return -1;
    if (o !== -1 && o < c) { depth++; i = o + 5; } else { depth--; if (depth === 0) return c + 7; i = c + 7; }
  }
  return -1;
}
let panels = 0;
html = html.replace(/<div class="(stepbox|keybox|warnbox|boardbox|panel)">([\s\S]*?)<\/div>/g, (m, cls, inner) => {
  const pStart = inner.indexOf("<p>");
  if (pStart === -1) return m;
  const spanStart = inner.indexOf("<span>", pStart);
  if (spanStart === -1) return m;
  const spanEnd = matchSpanEnd(inner, spanStart);
  if (spanEnd === -1) return m;
  const boxTitle = inner.slice(spanStart + 6, spanEnd - 7).trim();
  const pEnd = inner.indexOf("</p>", spanEnd);
  const rest = pEnd === -1 ? inner.slice(spanEnd) : inner.slice(spanEnd, pEnd);
  const afterP = pEnd === -1 ? "" : inner.slice(pEnd + 4);
  panels++;
  return `<div class="${cls}"><div class="box-title">${boxTitle}</div><div class="box-body">${(rest + afterP).trim()}</div></div>`;
});

/* ------------------------- 3. cross references ------------------------- */
let refs = 0;
html = html.replace(/<a[^>]*data-reference[^>]*>([^<]*)<\/a>/g, (m, txt) => {
  if (!/\?\?/.test(txt) && !/^\[(eq|sec|thm|lem|prop|cor|def|fig|tab)/.test(txt.trim())) return m;
  refs++;
  return '<span class="xref">（见对应公式/小节）</span>';
});

/* ------------------------- 4. leftover raw TeX ------------------------- */
let raw = 0;
html = html.replace(/<span class="math (?:display|inline)">([^<]*\$[^<]*)<\/span>/g, (m, tex) => {
  raw++;
  const plain = tex.replace(/\$+/g, "").replace(/\\[a-zA-Z]+\s*/g, "").replace(/[{}]/g, "").replace(/\s+/g, " ").trim();
  return `<span class="uni-math">${plain}</span>`;
});

/* ------------------------- 5. table wrappers ------------------------- */
html = html.replace(/(<table>[\s\S]*?<\/table>)/g, '<div class="table-wrap">$1</div>');

/* ------------------------- 6. title block ------------------------- */
html = html.replace(/<h1 class="title">[\s\S]*?<\/h1>/,
  `<h1 class="title">${esc(title)}</h1>` + (subtitle ? `\n<p class="doc-sub">${esc(subtitle)}</p>` : ""));

/* ------------------------- 7. style / wrapper / footer ------------------------- */
const css = fs.existsSync(cssPath)
  ? fs.readFileSync(cssPath, "utf8")
  : "body{font-family:Georgia,'Noto Serif CJK SC',serif;line-height:1.8;max-width:900px;margin:0 auto;padding:2em}";

const aiNote = `<div class="ai-note"><p>This page was generated by DeepSeek 4.1 Flash from the course source; derivations and numbers are reproduced verbatim.</p>
<p>本页由 DeepSeek 4.1 Flash 依据课程讲义生成，推导与数值均按原讲义保留。</p></div>`;

const nav = `<nav class="toc">\n<a class="back" href="${esc(back)}">&#8592; ${esc(backLabel)}</a>\n<div class="toc-title">目录 Contents</div>\n<ul id="toc-list"></ul>\n</nav>`;

const tocScript = `<script>
document.addEventListener('DOMContentLoaded', function () {
  var page = document.querySelector('.page');
  var list = document.getElementById('toc-list');
  if (!page || !list) return;
  page.querySelectorAll('h1,h2').forEach(function (h) {
    if (h.classList.contains('title')) return;
    var t = (h.childNodes[0] ? h.childNodes[0].textContent : h.textContent).trim();
    if (!t) return;
    if (!h.id) h.id = 'sec-' + Math.abs(t.split('').reduce(function (a, c) { return (a * 31 + c.charCodeAt(0)) | 0; }, 7));
    var li = document.createElement('li');
    li.className = 'toc-' + h.tagName.toLowerCase();
    var a = document.createElement('a');
    a.href = '#' + h.id;
    a.textContent = t;
    li.appendChild(a);
    list.appendChild(li);
  });
});
</script>`;

html = html.replace(/<html[^>]*>/, '<html lang="zh-CN">');
html = html.replace("</head>", `  <style>${css}</style>\n</head>`);
html = html.replace(/<body[^>]*>/, `<body>\n<div class="layout">\n${nav}\n<div class="page">`);
html = html.replace(/<\/body>/, `${aiNote}\n</div>\n</div>\n${tocScript}\n</body>`);

fs.writeFileSync(output, html, "utf8");
console.log(`wrote ${output} (${fs.statSync(output).size} bytes)`);
console.log(`panels split: ${panels} | xrefs replaced: ${refs} | raw-TeX spans: ${raw}`);
if (!/<h1/.test(html)) console.warn("WARNING: no <h1> in output — check the pandoc run (headings may have become \\\\section line breaks)");
